import django.db.models as models

class Designation(models.Model):
    name = models.CharField(max_length=256, unique=True, null=True, blank=True, help_text='Name of the designation (max 256 characters)')
    code = models.CharField(max_length=256, unique=True, null=True, blank=True, help_text='Code of the designation (max 256 characters)')
    department = models.ForeignKey('Department', related_name='designations', on_delete=models.CASCADE, null=True, blank=True, help_text='Department of the designation')
    is_active = models.BooleanField(default=True, help_text='Is the designation active?')
    created_at = models.DateTimeField(auto_now_add=True, help_text='Date and time when the designation was created')
    updated_at = models.DateTimeField(auto_now=True, help_text='Date and time when the designation was last updated')

    def __str__(self):
        return self.name

































































































































































































        